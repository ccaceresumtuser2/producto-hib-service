-- Tabla de productos
CREATE TABLE IF NOT EXISTS productos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo         VARCHAR(8)     NOT NULL,
    nombre         VARCHAR(100)   NOT NULL,
    descripcion    VARCHAR(255),
    precio         NUMERIC(12, 2) NOT NULL,
    stock          INTEGER        NOT NULL,
    categoria      VARCHAR(20)    NOT NULL,
    activo         BOOLEAN        NOT NULL,
    fecha_creacion TIMESTAMP(6)   NOT NULL,

    CONSTRAINT productos_pkey         PRIMARY KEY (id),
    CONSTRAINT uk_productos_codigo    UNIQUE (codigo),
    CONSTRAINT ck_productos_codigo    CHECK (codigo ~ '^[A-Z]{3}-[0-9]{4}$'),
    CONSTRAINT ck_productos_precio    CHECK (precio > 0),
    CONSTRAINT ck_productos_stock     CHECK (stock >= 0),
    CONSTRAINT ck_productos_categoria CHECK (categoria IN ('TECNOLOGIA', 'HOGAR', 'ROPA', 'ALIMENTOS', 'OTROS'))
);

-- Búsquedas por nombre
CREATE INDEX IF NOT EXISTS idx_productos_nombre ON productos (nombre);

-- Filtro por categoría
CREATE INDEX IF NOT EXISTS idx_productos_categoria ON productos (categoria);

-- Filtro combinado: productos activos de una categoría
CREATE INDEX IF NOT EXISTS idx_productos_categoria_activo ON productos (categoria, activo);
